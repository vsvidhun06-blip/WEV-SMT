#!/usr/bin/env python3
"""AUDIT obligation O17 -- differential test of the reconstructed composition model
against the SHIPPED Java detector.

T2 rests entirely on the claim that

    S_f(x, e) = OR over reg in ids(e) of [ f(e,reg) AND F(x, reg) ]
    F(x, reg) = true if reg is the load, else S_f(x, def(reg))

faithfully describes LitmusParser.referencedReads/deriveReg. That is an empirical claim
about Java, not a theorem. This script generates random blocks, emits a jshell script
that runs them through the real parser, and compares the shipped verdict against the
Python model in depprobe.site_real.

Stage 1 (this script):  python eval/research/a4_differential.py gen  N
Stage 2 (jshell):       run the emitted .jsh, capture output to a file
Stage 3:                python eval/research/a4_differential.py cmp  <output-file>
"""
import sys, os, random, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from depprobe import Block, site_real, subst_real

HERE = os.path.dirname(os.path.abspath(__file__))
JSH = os.path.join(HERE, "a4_gen.jsh")
SPEC = os.path.join(HERE, "a4_spec.json")

# TWO front-end constraints discovered by direct probe (scratchpad/audit2.jsh); both are
# LEXER artifacts and must be avoided or the test measures the lexer, not the composition:
#
#   (1) WRITE_ONCE(*y, <value>) TRUNCATES the value at the FIRST ')'. Probe:
#         WRITE_ONCE(*y, ((~(r0 ^ r0)) - (255 | r0)))  ->  detector sees '((~(r0 ^ r0'
#         WRITE_ONCE(*y, (r0) )                        ->  detector sees '(r0'
#       => emit NO parentheses anywhere in a value expression.
#   (2) '|' is the litmus THREAD-COLUMN SEPARATOR. `WRITE_ONCE(*y, 255 | r0)` raises
#       UNSUPPORTED_INSTRUCTION because the row is split into two thread columns.
#       => '|' is unusable in this dialect.
#
# `*` is also excluded: the C dialect uses it for dereference.
OPS = ["+", "-", "&", "^"]


def rand_expr(rng, regs, d):
    """Flat, parenthesis-free, pipe-free expression (see the constraints above)."""
    n = rng.choice([1, 2, 2, 3, 3, 4])
    terms = []
    for _ in range(n):
        if rng.random() < 0.72:
            t = rng.choice(regs)
        else:
            t = str(rng.choice([0, 1, 2, 3, 7, 255]))
        if rng.random() < 0.12:
            t = "~" + t
        terms.append(t)
    out = terms[0]
    for t in terms[1:]:
        out += " %s %s" % (rng.choice(OPS), t)
    return out


def gen(n):
    rng = random.Random(0xA4D1FF)
    specs = []
    for i in range(n):
        avail = ["r0"]
        defs = []
        for k in range(rng.choice([1, 1, 2, 2, 3])):
            defs.append(("t%d" % k, rand_expr(rng, avail, rng.choice([1, 2]))))
            avail.append("t%d" % k)
        store = rand_expr(rng, avail, rng.choice([1, 2]))
        specs.append({"defs": defs, "store": store})

    with open(SPEC, "w") as fh:
        json.dump(specs, fh)

    lines = [
        '// generated by a4_differential.py -- differential test of the composition model',
        'String hdr = "C T\\n{ }\\n";',
        'java.util.function.BiConsumer<String,String> go = (id, body) -> {',
        '  try {',
        '    var lc = wev.smt.parse.LitmusParser.parse(hdr + body, "t.litmus");',
        '    long sem = lc.deps().allEdges().stream().filter(e -> e.edge().isSemantic()).count();',
        '    long tot = lc.deps().allEdges().size();',
        '    System.out.println("RESULT " + id + " " + tot + " " + sem);',
        '  } catch (Throwable t) { System.out.println("RESULT " + id + " ERR ERR"); }',
        '};',
    ]
    for i, sp in enumerate(specs):
        body = " P0                        ;\\n r0 = READ_ONCE(*x)        ;\\n"
        for nm, e in sp["defs"]:
            body += " %s = %s        ;\\n" % (nm, e)
        body += " WRITE_ONCE(*y, %s)        ;\\nexists (0:r0=1)\\n" % sp["store"]
        lines.append('go.accept("%d", "%s");' % (i, body))
    lines.append("/exit")
    with open(JSH, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("generated %d programs" % n)
    print("  spec : %s" % SPEC)
    print("  jsh  : %s" % JSH)


def cmp(path):
    specs = json.load(open(SPEC))
    shipped = {}
    for line in open(path, errors="replace"):
        line = line.strip()
        if not line.startswith("RESULT "):
            continue
        p = line.split()
        if len(p) != 4:
            continue
        shipped[int(p[1])] = p[3]

    agree = dis = err = skipped = 0
    mismatches = []
    for i, sp in enumerate(specs):
        if i not in shipped:
            skipped += 1
            continue
        if shipped[i] == "ERR":
            err += 1
            continue
        ship_real = int(shipped[i]) > 0
        blk = Block(["r0"], [(n, e) for n, e in sp["defs"]], sp["store"])
        try:
            model_real = site_real(blk, "r0")
        except Exception:
            skipped += 1
            continue
        if ship_real == model_real:
            agree += 1
        else:
            dis += 1
            if len(mismatches) < 12:
                mismatches.append((i, blk.pretty(),
                                   "REAL" if ship_real else "FAKE",
                                   "REAL" if model_real else "FAKE"))

    print("=== O17 differential test: reconstructed model vs shipped Java ===")
    print("   programs compared : %d" % (agree + dis))
    print("   AGREE             : %d" % agree)
    print("   DISAGREE          : %d" % dis)
    print("   parse errors      : %d   (excluded -- front-end lexing, not composition)" % err)
    print("   skipped           : %d" % skipped)
    if mismatches:
        print("\n   *** MODEL IS NOT FAITHFUL -- T2's statement must be re-derived ***")
        for i, b, s, m in mismatches:
            print("     #%-4d %-52s shipped=%s model=%s" % (i, b[:52], s, m))
    else:
        print("\n   => no divergence. O17 upgraded from ASSUMED to TESTED.")

    # Bonus: how often does the shipped detector disagree with ground truth?
    wrong = 0
    for i, sp in enumerate(specs):
        if i not in shipped or shipped[i] == "ERR":
            continue
        blk = Block(["r0"], [(n, e) for n, e in sp["defs"]], sp["store"])
        try:
            if (int(shipped[i]) > 0) != subst_real(blk, "r0"):
                wrong += 1
        except Exception:
            pass
    print("\n   shipped detector vs GROUND TRUTH on the same corpus: %d disagreements"
          % wrong)
    print("   (every one is an over-approximation: a fake edge reported real)")


if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "gen":
        gen(int(sys.argv[2]) if len(sys.argv) > 2 else 200)
    elif len(sys.argv) >= 3 and sys.argv[1] == "cmp":
        cmp(sys.argv[2])
    else:
        print(__doc__)
