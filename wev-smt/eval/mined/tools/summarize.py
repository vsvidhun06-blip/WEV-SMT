#!/usr/bin/env python3
"""Phase B step 5 -- roll up the mined-suite results.

Reads  : eval/mined/candidates.csv, eval/mined/manifest.csv,
         eval/mined-discriminating.csv, eval/mined-discriminating-copyprop.csv
Writes : eval/mined-summary.md  (and prints the same to stdout)

Run from repo root:  python eval/mined/tools/summarize.py
"""
import collections
import sys
import csv
import os

E = "eval"
M = os.path.join(E, "mined")


def rd(p):
    with open(p, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


cand = rd(os.path.join(M, "candidates.csv"))
man = rd(os.path.join(M, "manifest.csv"))
disc = rd(os.path.join(E, "mined-discriminating.csv"))
cp = rd(os.path.join(E, "mined-discriminating-copyprop.csv"))

by = {r["test"]: r for r in disc}
bycp = {r["test"]: r for r in cp}
out = []
w = out.append

w("# eval/mined-summary.md — mined fake-dependency suite, roll-up")
w("")
w("Generated by `eval/mined/tools/summarize.py`. Numbers here are the authority for")
w("`findings-mined-suite.md`.")
w("")

# ── Phase A ────────────────────────────────────────────────────────────────────
w("## Phase A — mining")
w("")
srcs = sorted({r["source"] for r in cand})
w("| quantity | count |")
w("|---|---:|")
w("| kernel source files | %d |" % len(srcs))
w("| (compiler, arch) configurations | 4 |")
w("| assembly files produced | %d |" % len({r["asm_file"] for r in cand}))
w("| function blocks scanned | %d |" % len(cand))
w("| blocks with load→store register flow | %d |"
  % sum(1 for r in cand if r["flow"] == "load->store"))
w("| blocks whose dependency the compiler ERASED | %d |"
  % sum(1 for r in cand if r["screen"] == "absent"))
w("| blocks screened FAKE (flow present, value constant) | %d |"
  % sum(1 for r in cand if r["screen"] == "fake"))
w("| blocks screened REAL | %d |" % sum(1 for r in cand if r["screen"] == "real"))
w("")

w("### Fake-screened blocks, by source and configuration")
w("")
w("| source :: function | compiler | arch | emitted | note |")
w("|---|---|---|---|---|")
for r in cand:
    if r["screen"] != "fake":
        continue
    w("| `%s::%s` | %s | %s | %s | %s |"
      % (r["source"], r["func"], r["compiler"], r["arch"], r["emitted"], r["reason"] or "—"))
w("")

# ── Phase B ────────────────────────────────────────────────────────────────────
w("## Phase B — classification by the frozen detector")
w("")
w("Driver: `wev.smt.ablation.AnchorDiscriminatingRun` (frozen encoder + ")
w("`AxiomaticConsistency`, `maxEvents=64`, `timeoutSec=30`). `discriminating` means the")
w("WEAKEST verdict changes when `sdep` is replaced by `dep`.")
w("")
w("| suite | tests | fake edges seen by detector | discriminating |")
w("|---|---:|---:|---:|")
for label, rows in (("mined (as the compiler emitted it)", disc),
                    ("counterfactual (+ copy propagation)", cp)):
    w("| %s | %d | %d | **%d** |"
      % (label, len(rows),
         sum(int(r["dataFake"]) + int(r["addrFake"]) + int(r["ctrlFake"]) for r in rows),
         sum(1 for r in rows if r["discriminating"] == "true")))
w("")

w("### Per-test")
w("")
w("| test | idiom | screen | deps | fake | none | sdep=dep | sdep=detector | disc | disc(+cp) |")
w("|---|---|---|---:|---:|---|---|---|---|---|")
mman = {r["test"]: r for r in man}
for t in sorted(by):
    r, c = by[t], bycp.get(t, {})
    mm = mman.get(t, {})
    w("| `%s` | %s | %s | %s | %s | %s | %s | %s | %s | %s |"
      % (t.replace("mined_", ""), mm.get("idiom", "—"), mm.get("screen", "—"),
         r["dataDeps"], r["dataFake"], r["verdict_none"],
         r["verdict_all_deps_semantic"], r["verdict_current"],
         "**yes**" if r["discriminating"] == "true" else "no",
         "**yes**" if c.get("discriminating") == "true" else "no"))
w("")

# splits
w("### Splits over the fake-carrying mined tests")
w("")
fake_tests = [r for r in man if r["screen"] == "fake"]
for key, title in (("fake_edge_kind", "by fake-edge kind"), ("arch", "by arch"),
                   ("compiler", "by compiler"), ("idiom", "by idiom")):
    cnt = collections.Counter(r[key] for r in fake_tests)
    dcnt = collections.Counter(r[key] for r in fake_tests
                               if by.get(r["test"], {}).get("discriminating") == "true")
    ccnt = collections.Counter(r[key] for r in fake_tests
                               if bycp.get(r["test"], {}).get("discriminating") == "true")
    w("**%s**" % title)
    w("")
    w("| %s | mined | discriminating | discriminating (+copyprop) |" % key)
    w("|---|---:|---:|---:|")
    for k in sorted(cnt):
        w("| %s | %d | %d | %d |" % (k, cnt[k], dcnt.get(k, 0), ccnt.get(k, 0)))
    w("")

# ── front-end blind spots ──────────────────────────────────────────────────────
w("## Blocks the front end cannot see (W2 targets, not failures)")
w("")
w("| reason | blocks |")
w("|---|---:|")
reasons = collections.Counter(r["reason"] for r in cand if r["reason"])
for k, v in reasons.most_common():
    w("| %s | %d |" % (k, v))
w("")

txt = "\n".join(out) + "\n"
with open(os.path.join(E, "mined-summary.md"), "w", encoding="utf-8") as fh:
    fh.write(txt)
print(txt.encode("utf-8", "replace").decode(sys.stdout.encoding or "utf-8", "replace"))
